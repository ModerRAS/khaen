//! 方案组装：把设计/校准产物（通道布局、分频、矩阵、保护增益、路由）拼成 plan ABI v3。
//!
//! 职责边界：
//! - **只做组装与序列化**：`khaen_core::plan::Plan` 已负责 ABI v3 的编码/解码与校验，
//!   本 crate 负责"把人的意图变成合法的 Plan"，并把错误翻成可读的组装错误。
//! - **不做 DSP**：不卷积、不拟合、不碰实时路径。
//! - 组装结果必须能被 `Plan::encode` 编出、被 `Plan::decode` 原样解回、被 `khaen_host` 的
//!   准入与图编译接受；这三点由测试锁住，缺一不算完成。
//!
