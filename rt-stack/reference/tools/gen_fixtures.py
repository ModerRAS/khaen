def build_fixture(case: dict) -> dict:
    res = compute_expected(case)
    sp = res["supports"]
    expected = check_and_serialize_expected(res["expected"], case["comparison"])
    graph = dict(
        n_src=sp["n_src"],
        n_out=sp["n_out"],
        container_channels=res["container_channels"],
        d_samples=int(case["d_samples"]),
        a_map=case["a_map"],
        a_fir=case["a_fir"],
        participants=case["participants"],
        g=case["g"],
        p=case["p"],
        scatter=case["scatter"],
    )
    fixture = dict(
        schema=SCHEMA,
        id=case["id"],
        title=case["title"],
        tags=list(case["tags"]),
        fs_hz=case["fs_hz"],
        generated_by=GEN_NAME,
        graph=graph,
        supports=dict(
            l_a=sp["l_a"],
            l_g=sp["l_g"],
            l_p=sp["l_p"],
            l_f=sp["l_f"],
            l_out=sp["l_out"],
        ),
        input=case["input"],
        expected=expected,
        expected_len=sp["l_out"],
        comparison=case["comparison"],
        streaming=dict(
            block_sizes=list(case["streaming"]),
            flush_zeros=sp["l_f"] - 1,
            contract="pad input with flush_zeros zeros, process in blocks of B, concatenate and truncate to expected_len",
        ),
        notes=case.get("notes", ""),
    )
    if case.get("traps"):
        fixture["traps"] = case["traps"]
    return fixture


def dump_json(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def generated_files():
    files = {}
    index_cases = []
    ids = set()
    for case in CASES:
        if case["id"] in ids:
            raise ValueError(f"duplicate case id {case['id']}")
        ids.add(case["id"])
        fixture = build_fixture(case)
        name = case["id"] + ".json"
        text = dump_json(fixture)
        files[Path("cases") / name] = text
        index_cases.append(dict(
            id=case["id"],
            file=f"cases/{name}",
            tags=list(case["tags"]),
            comparison=case["comparison"]["mode"],
            sha256=hashlib.sha256(text.encode("utf-8")).hexdigest(),
            bytes=len(text.encode("utf-8")),
        ))
    index = dict(
        schema=INDEX_SCHEMA,
        generated_by=GEN_NAME,
        cases=index_cases,
    )
    files[Path("index.json")] = dump_json(index)
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help="write fixtures (default is --check)")
    g.add_argument("--check", action="store_true", help="compare on-disk files with freshly generated bytes")
    args = ap.parse_args(argv)
    if not args.write and not args.check:
        args.check = True
    files = generated_files()
    if args.write:
        for rel, text in files.items():
            path = REF_ROOT / "fixtures" / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(REF_ROOT)} ({len(text.encode('utf-8'))} bytes)")
        print(f"OK: {len(CASES)} cases + index generated")
        return 0
    # check mode
    problems = []
    for rel, text in files.items():
        path = REF_ROOT / "fixtures" / rel
        if not path.exists():
            problems.append(f"missing: {path}")
            continue
        disk = path.read_bytes()
        want = text.encode("utf-8")
        if disk != want:
            problems.append(f"mismatch: {path} (disk {len(disk)} bytes, generated {len(want)} bytes)")
    for p in sorted((REF_ROOT / "fixtures" / "cases").glob("*.json")):
        rel = Path("cases") / p.name
        if rel not in files:
            problems.append(f"stale file not generated by this script: {p}")
    if problems:
        for p in problems:
            print("FAIL:", p, file=sys.stderr)
        return 1
    print(f"OK: {len(CASES)} fixtures + index are byte-identical to generated content")
    return 0


if __name__ == "__main__":
    sys.exit(main())
