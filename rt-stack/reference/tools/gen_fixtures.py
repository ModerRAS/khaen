def frac(v) -> Fraction:
    if isinstance(v, Fraction):
        return v
    if isinstance(v, int):
        return Fraction(v)
    if isinstance(v, float):
        return Fraction(v)  # exact binary64 value
    raise TypeError(f"unsupported numeric literal: {v!r}")


def as_frac_list(xs):
    return [frac(v) for v in xs]


def poly_conv(a, b):
    """exact polynomial multiplication (a,b are lists of Fractions)"""
    if len(a) == 0 or len(b) == 0:
        return []
    out = [Fraction(0)] * (len(a) + len(b) - 1)
    for i, ai in enumerate(a):
        if ai == 0:
            continue
        for j, bj in enumerate(b):
            if bj != 0:
                out[i + j] += ai * bj
    return out


def supports_of(case: dict) -> dict:
    n_src = len(case["input"])
    n_out = len(case["p"])
    m = len(case["participants"])
    d = int(case["d_samples"])
    a_fir = case["a_fir"]
    g = case["g"]
    p = case["p"]
    if len(a_fir) != n_src:
        raise ValueError("a_fir length != n_src")
    if len(g) != m or any(len(row) != m for row in g):
        raise ValueError("g must be MxM FIR matrix")
    if len(p) != n_out:
        raise ValueError("p length != n_out")
    l_a = max(len(v) for v in a_fir)
    max_g_idx = -1
    for row in g:
        for cell in row:
            for t, v in enumerate(cell):
                if frac(v) != 0:
                    max_g_idx = max(max_g_idx, t)
    l_g = max(d + 1, max_g_idx + 1)
    l_p = max(len(v) for v in p)
    l_f = l_a + l_g + l_p - 2
    lengths = {len(v) for v in case["input"]}
    if len(lengths) != 1:
        raise ValueError("all input channel arrays must share one length")
    l_x = lengths.pop()
    return dict(l_a=l_a, l_g=l_g, l_p=l_p, l_f=l_f, l_out=l_x + l_f - 1, l_x=l_x, n_src=n_src, n_out=n_out, m=m)


def build_g_full(case: dict, l_g: int):
    """G_full[j][k] as list of Fractions of length l_g (D baseline + embedded g)."""
    n_out = len(case["p"])
    d = int(case["d_samples"])
    m = len(case["participants"])
    participants = list(case["participants"])
    assert len(participants) == m and len(set(participants)) == m
    G = [[[Fraction(0)] * l_g for _ in range(n_out)] for _ in range(n_out)]
    for j in range(n_out):
        G[j][j][d] += Fraction(1)
    for a in range(m):
        for b in range(m):
            j = participants[a]
            k = participants[b]
            for t, v in enumerate(case["g"][a][b]):
                G[j][k][t] += frac(v)
    return G


def compute_expected(case: dict) -> dict:
    sp = supports_of(case)
    n_src, n_out, m = sp["n_src"], sp["n_out"], sp["m"]
    l_g, l_out = sp["l_g"], sp["l_out"]
    participants = list(case["participants"])
    assert len(participants) == len(set(participants))
    scatter = list(case["scatter"])
    if len(scatter) != n_out or len(set(scatter)) != n_out:
        raise ValueError("scatter must be an injective O->container map")
    if any(c < 0 for c in scatter):
        raise ValueError("scatter index must be >= 0")
    C = max(1, max(scatter) + 1, int(case.get("container_channels", 0)))
    # input-side FIRs
    u_src = []
    for i in range(n_src):
        u_src.append(poly_conv(as_frac_list(case["a_fir"][i]), as_frac_list(case["input"][i])))
    # role-domain selected signals, zero filled
    a_map = case["a_map"]
    if len(a_map) != n_out or any(len(row) != n_src for row in a_map):
        raise ValueError("a_map must be O x N")
    l_u = sp["l_x"] + sp["l_a"] - 1
    u_role = []
    for j in range(n_out):
        row = a_map[j]
        ones = [i for i, v in enumerate(row) if v not in (0, 1)]
        if ones:
            raise ValueError("a_map entries must be 0 or 1")
        idx = [i for i, v in enumerate(row) if v == 1]
        if len(idx) > 1:
            raise ValueError("a_map row may select at most one source")
        if idx:
            src = idx[0]
            u = list(u_src[src])
            if len(u) < l_u:
                u = u + [Fraction(0)] * (l_u - len(u))
            u_role.append(u)
        else:
            u_role.append([Fraction(0)] * l_u)
    # every source may be selected by at most one row (pure selection, no fan-out/mixing)
    selected = [i for row in a_map for i, v in enumerate(row) if v == 1]
    if len(selected) != len(set(selected)):
        raise ValueError("a_map must be injective (no source fan-out)")
    # G stage
    G = build_g_full(case, l_g)
    v = []
    for j in range(n_out):
        acc = [Fraction(0)] * (l_u + l_g - 1)
        for k in range(n_out):
            c = poly_conv(G[j][k], u_role[k])
            for t, val in enumerate(c):
                acc[t] += val
        v.append(acc)
    # P stage.  l_out is the declared common output length; a route whose
    # actual support is shorter than the declared common limit is right-padded
    # with zeros (declared supports, not actual non-zero spans, define length).
    y = []
    for j in range(n_out):
        yj = poly_conv(as_frac_list(case["p"][j]), v[j])
        assert len(yj) <= l_out, (j, len(yj), l_out)
        yj = yj + [Fraction(0)] * (l_out - len(yj))
        y.append(yj)
    z = [[Fraction(0)] * l_out for _ in range(C)]
    for j in range(n_out):
        z[scatter[j]] = list(y[j])
    return dict(supports=sp, expected=z, container_channels=C)


