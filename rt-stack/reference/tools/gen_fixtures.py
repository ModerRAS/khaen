    mode = comparison["mode"]
    out = []
    for ch in frac_expected:
        arr = []
        for v in ch:
            if mode == "exact":
                f = float(v)
                if Fraction(f) != v:
                    raise ValueError(f"exact case value not representable in binary64: {v}")
                if abs(f) >= 2.0 ** 53:
                    raise ValueError(f"exact case value too large for exact f64 arithmetic: {f}")
                arr.append(int(v) if v.denominator == 1 else f)
            elif mode == "tolerance":
                arr.append(float(v))  # single correct rounding of exact real value
            else:
                raise ValueError(f"unknown comparison mode: {mode}")
        out.append(arr)
    return out


