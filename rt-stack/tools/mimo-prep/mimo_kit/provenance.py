class ProvenanceRefusal(Exception):
    """Raised when a design/H/plan must not be issued."""

    def __init__(self, codes, detail=None):
        self.codes = list(codes) if isinstance(codes, (list, tuple)) else [codes]
        self.detail = detail or {}
        super().__init__("PROVENANCE_REFUSED: " + ", ".join(self.codes))


def _f(v, default=None):
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _canon_bytes(arrays):
    h = hashlib.sha256()
    for name in sorted(arrays):
        a = np.ascontiguousarray(arrays[name])
        if a.dtype.kind == "c":
            a = a.astype(np.complex128)
        else:
            a = a.astype(np.float64)
        h.update(name.encode("utf-8") + b"\x00")
        h.update(str(a.shape).encode("ascii") + b"\x00")
        h.update(a.tobytes())
    return h.hexdigest()


def canonical_arrays_sha(arrays):
    return _canon_bytes(dict(arrays))


def load_npz(path):
    z = np.load(path, allow_pickle=True)
    try:
        return {k: z[k] for k in z.files}
    finally:
        z.close()


def load_json(path, default=None):
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return default


