    dryrun = os.path.join(ev, "mimo-pilot-3mic", "prep", "dryrun", "out")
    planrt = os.path.join(ev, "mimo-pilot-3mic", "planrt-20261119")
    reg = {"schema": "tspi-mimo-synthetic-registry/v1", "project": project,
           "synthetic_design_sha256": {}, "synthetic_plan_sha256": {},
           "synthetic_h_sha256": {}, "synthetic_G_ideal_sha256": None,
           "dryrun_design_dir": None, "notes": []}
    # dry-run reference design + H
    dd = os.path.join(dryrun, "design", "g_design.npz")
    if os.path.isfile(dd):
        reg["dryrun_design_dir"] = os.path.dirname(os.path.dirname(dd))
        reg["synthetic_design_sha256"]["dryrun/design/g_design.npz"] = sha256_file(dd)
        z = load_npz(dd)
        reg["synthetic_G_ideal_sha256"] = canonical_arrays_sha({"G_ideal": z["G_ideal"]})
