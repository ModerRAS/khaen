def _sha256_f64_array(a):
    """Canonical sha256 of a float64 coefficient block (mimo_v2.sha256_arr semantics)."""
    return hashlib.sha256(np.ascontiguousarray(np.asarray(a, dtype=np.float64)).tobytes()).hexdigest()


def _load_f32(path, shape=None):
    a = np.fromfile(os.fspath(path), dtype="<f4").astype(np.float64)
    if shape is not None:
        a = a.reshape(shape)
    return a


def _as_int(v, default=None):
    try:
        return int(v)
    except (TypeError, ValueError):
        return default


def _claim_12k_tags_synthetic(text):
    """True when a free-text claim tags the artifact synthetic/dry-run (negations ignored)."""
    t = str(text or "").lower()
    for neg in ("not a dry-run", "not dry-run", "not a synthetic", "not synthetic",
                "no dry-run", "no synthetic", "non-synthetic", "non synthetic",
                "never synthetic", "not from the dry-run", "not from dry-run"):
        t = t.replace(neg, "")
    return ("dry-run" in t) or ("dryrun" in t) or ("synthetic" in t)


def _code_fail(codes, reasons, code, msg=None):
    if code not in codes:
        codes.append(code)
    reasons.setdefault(code, msg or _A12_REASON_TEXT.get(code, code))


def synthetic_registry_12k(project=None):
    """Content-addressed registry of synthetic 12k fixtures (computed from the repo).

    Sources of "must never be issued as a real-room 12k G":
      * the dry-run synthetic H (48 kHz 7-output guard format);
      * every fixture directory under evidence/mimo-12k-provenance/synthetic-12k*,
        which the task-255 packager generates from that dry-run H.
    """
    project = project or PROJECT
    ev = os.path.join(project, "rt-stack", "evidence")
    dryrun = os.path.join(ev, "mimo-pilot-3mic", "prep", "dryrun")
    planrt = os.path.join(ev, "mimo-pilot-3mic", "planrt-20261119", "plans")
    prov_root = os.path.join(ev, "mimo-12k-provenance")
    reg = {"schema": "tspi-mimo-12k-synthetic-registry/v1", "project": project,
           "synthetic_h_sha256": {}, "synthetic_g12_file_sha256": {},
           "synthetic_g12_content_sha256": {}, "synthetic_params_sha256": {},
           "synthetic_roots": [os.path.join(dryrun, "out"), planrt,
                               os.path.join(prov_root, "synthetic-12k")],
           "fixtures": {}, "notes": []}
    hh = os.path.join(dryrun, "out", "h", "h_estimate.npz")
    if os.path.isfile(hh):
        reg["synthetic_h_sha256"]["dryrun/out/h/h_estimate.npz"] = sha256_file(hh)
    if os.path.isdir(prov_root):
        for name in sorted(os.listdir(prov_root)):
            if name != "synthetic-12k" and not name.startswith("synthetic-12k"):
                continue
            d = os.path.join(prov_root, name)
            if not os.path.isdir(d):
                continue
            pj = os.path.join(d, "params.json")
            params = load_json(pj, None)
            if not isinstance(params, dict):
                continue
            key = "mimo-12k-provenance/" + name
            gfile = os.path.join(d, str(params.get("g_file") or "g12_v2_4096.f32"))
            fx = {"dir": os.path.abspath(d),
                  "params_sha256": sha256_file(pj),
                  "g_file": os.path.basename(gfile)}
            if os.path.isfile(gfile):
                fx["g_file_sha256"] = sha256_file(gfile)
                reg["synthetic_g12_file_sha256"][key] = fx["g_file_sha256"]
                taps = _as_int(params.get("taps"), A12_TAPS)
                parts = params.get("participants") or A12_PARTICIPANTS
                try:
                    arr = _load_f32(gfile, (len(parts), len(parts), taps))
                    fx["g_f32_content_sha256"] = _sha256_f64_array(arr)
                    reg["synthetic_g12_content_sha256"][key] = fx["g_f32_content_sha256"]
                except (OSError, ValueError):
                    pass
            prov = load_json(os.path.join(d, "provenance.json"), None)
            if isinstance(prov, dict):
                hsha = (prov.get("h") or {}).get("sha256")
                if hsha:
                    reg["synthetic_h_sha256"][key] = str(hsha)
            reg["synthetic_params_sha256"][key] = fx["params_sha256"]
            reg["fixtures"][key] = fx
    reg["notes"].append("synthetic 12k fixtures are generated from the dry-run synthetic H by "
                        "tools/mimo-prep/mimo12k_guard.py make-synthetic; they are refused by "
                        "g12_artifact_guard (markers, dry-run source, registered content)")
    return reg


def synthetic_g12_arrays(project=None):
    """Load the registered synthetic 12k G arrays for the <=1e-12 content comparison."""
    reg = synthetic_registry_12k(project)
    out = {}
    for key, fx in (reg.get("fixtures") or {}).items():
        p = os.path.join(fx["dir"], fx.get("g_file") or "g12_v2_4096.f32")
        if not os.path.isfile(p):
            continue
        params = load_json(os.path.join(fx["dir"], "params.json"), {}) or {}
        taps = _as_int(params.get("taps"), A12_TAPS)
        parts = params.get("participants") or A12_PARTICIPANTS
        try:
            out[key] = _load_f32(p, (len(parts), len(parts), taps))
        except (OSError, ValueError):
            continue
    return out


# ---------------------------------------------------------------- 12k H guard
def h12_source_check(h_npz, fs_hz=None):
    """Validate the 48 kHz measured H that the 12k domain is extracted from."""
    codes, reasons, metrics = [], {}, {}
    path = os.path.abspath(os.fspath(h_npz))
    metrics["h_npz"] = path
    if not os.path.isfile(path):
        _code_fail(codes, reasons, "h12_source_missing",
                   "H npz not found; cannot prove the 12k G came from a measured arm")
        return {"ok": False, "codes": codes, "reasons": reasons, "metrics": metrics}
    try:
        z = load_npz(path)
    except (OSError, ValueError) as exc:
        _code_fail(codes, reasons, "h12_bad_format", "unreadable H npz: %r" % (exc,))
        return {"ok": False, "codes": codes, "reasons": reasons, "metrics": metrics}
    fs = float(fs_hz or A12_FS_48)
    metrics["fs_hz"] = fs
    participant_slots = [rd.ROLE_TO_SLOT[p] for p in A12_PARTICIPANTS]  # 0,1,2,3,7
    mic_data, mics, fmt = {}, [], None
    if "H_norm" in z or ("irs" in z and "mic_names" in z):
        Hn = np.asarray(z.get("H_norm", z.get("H_raw")), dtype=np.complex128)
        irs = np.asarray(z.get("irs"))
        mics = [str(x) for x in z.get("mic_names")] if "mic_names" in z else list(rd.DESIGN_MICS)
        fmt = "guard-format/48k-7-output"
        if Hn.ndim != 3 or irs.ndim != 3 or Hn.shape[:2] != irs.shape[:2] \
                or Hn.shape[1] != len(rd.OUTPUTS):
            _code_fail(codes, reasons, "h12_bad_shape",
                       "guard-format H must be (nm,7,nf) + irs (nm,7,ns), got %s/%s"
                       % (Hn.shape, irs.shape))
        else:
            for mi, m in enumerate(mics):
                H8 = np.zeros((8, Hn.shape[2]), dtype=np.complex128)
                ir8 = np.zeros((8, irs.shape[2]), dtype=np.float64)
                for row, (_nm, slot) in enumerate(rd.OUTPUTS):
                    H8[slot] = Hn[mi, row, :]
                    ir8[slot] = irs[mi, row, :]
                mic_data[m] = {"H": H8, "ir": ir8}
    elif any(str(k).startswith("H_") for k in z):
        mics = sorted(str(k)[2:] for k in z if str(k).startswith("H_"))
        fmt = "mimo-v2/48k-8-slot"
        for m in mics:
            Hm = np.asarray(z["H_" + m], dtype=np.complex128)
            irm = np.asarray(z.get("ir_" + m)) if ("ir_" + m) in z else None
            if Hm.ndim != 2:
                _code_fail(codes, reasons, "h12_bad_shape", "H_%s must be 2-D, got %s"
                           % (m, (Hm.shape,)))
                continue
            if irm is None or irm.ndim != 2:
                _code_fail(codes, reasons, "h12_bad_ir", "ir_%s missing/not 2-D" % m)
                continue
            mic_data[m] = {"H": Hm, "ir": np.asarray(irm, dtype=np.float64)}
    else:
        _code_fail(codes, reasons, "h12_bad_format",
                   "unrecognised H npz (want H_<mic>/ir_<mic> or H_norm/irs/mic_names)")
    freq = np.asarray(z.get("freq")) if "freq" in z else None
    metrics["mic_names"] = mics
    metrics["format"] = fmt
    if freq is None or freq.ndim != 1 or freq.size < 8:
        _code_fail(codes, reasons, "h12_bad_freq_grid", "H freq grid missing/short")
    if len(mics) < 3:
        _code_fail(codes, reasons, "h12_insufficient_mics",
                   "need >=3 design mics (UMIK/MA1/ARC), got %s" % (mics,))
    for m in rd.DESIGN_MICS:
        if m not in mics:
            _code_fail(codes, reasons, "h12_missing_mic",
                       "required design mic %s missing (got %s)" % (m, mics))
    max_peak = int(round(IR_MAX_PEAK_MS / 1000.0 * fs))
    max_spread = int(round(IR_MAX_PEAK_SPREAD_MS / 1000.0 * fs))
    peaks, peaks_ms, row_db, mic_peak_abs = {}, {}, {}, {}
    for m in mics:
        d = mic_data.get(m)
        if not d:
            continue
        Hm, irm = d["H"], d["ir"]
        if not np.all(np.isfinite(Hm)):
            _code_fail(codes, reasons, "h12_nonfinite", "%s H contains NaN/Inf" % m)
        if not np.all(np.isfinite(irm)):
            _code_fail(codes, reasons, "h12_nonfinite", "%s IR contains NaN/Inf" % m)
        abs_ir = float(np.max(np.abs(irm))) if irm.size else 0.0
        mic_peak_abs[m] = abs_ir
        if abs_ir <= A12_SILENT_IR_ABS:
            _code_fail(codes, reasons, "h12_silent_mic", "%s IR is silent (max %.3g)" % (m, abs_ir))
        pm, pms, dbm = {}, {}, {}
        row_max = {}
        for slot in participant_slots:
            if slot >= Hm.shape[0] or slot >= irm.shape[0]:
                continue
            hrow = np.abs(Hm[slot, :])
            row_max[slot] = float(np.max(hrow)) if hrow.size else 0.0
            ir = np.asarray(irm[slot], dtype=np.float64)
            if ir.size == 0 or not np.any(ir):
                continue
            k = int(np.argmax(np.abs(ir)))
            pm[slot] = k
            pms[slot] = round(k / fs * 1000.0, 3)
            if k > max_peak:
                _code_fail(codes, reasons, "h12_ir_peak_out_of_window",
                           "%s/slot%d IR peak at %.1f ms (> %.0f ms)"
                           % (m, slot, k / fs * 1000.0, IR_MAX_PEAK_MS))
        mic_max = max(row_max.values()) if row_max else 0.0
        for slot, rm in row_max.items():
            if mic_max <= 0.0:
                _code_fail(codes, reasons, "h12_dead_participant_row",
                           "%s/slot%d H has no measured energy" % (m, slot))
                continue
            rel = 20.0 * math.log10(rm / mic_max + 1e-300)
            dbm[slot] = round(rel, 2)
            if rel < A12_ROW_DEATH_DB:
                _code_fail(codes, reasons, "h12_dead_participant_row",
                           "%s/slot%d H is dead (%.1f dB below the mic's loudest row)" % (m, slot, rel))
        peaks[m] = pm
        peaks_ms[m] = pms
        row_db[m] = dbm
        vals = list(pm.values())
        if len(vals) >= 2 and (max(vals) - min(vals)) > max_spread:
            _code_fail(codes, reasons, "h12_ir_peak_spread",
                       "%s IR peaks span %d samples (> %d) across participant roles"
                       % (m, max(vals) - min(vals), max_spread))
    for slot in participant_slots:
        vals = [peaks[m][slot] for m in peaks if slot in peaks[m]]
        if len(vals) >= 2 and (max(vals) - min(vals)) > max_spread:
            _code_fail(codes, reasons, "h12_ir_peak_spread",
                       "slot%d IR peaks span %d samples across mics (> %d)"
                       % (slot, max(vals) - min(vals), max_spread))
    metrics.update({"peaks_samples": peaks, "peaks_ms": peaks_ms,
                    "row_level_db": row_db, "mic_ir_max_abs": mic_peak_abs,
                    "max_peak_allowed_samples": max_peak,
                    "max_spread_allowed_samples": max_spread,
                    "policy": {"ir_max_peak_ms": IR_MAX_PEAK_MS,
                               "ir_max_peak_spread_ms": IR_MAX_PEAK_SPREAD_MS,
                               "row_death_db": A12_ROW_DEATH_DB,
                               "silent_ir_abs": A12_SILENT_IR_ABS}})
    return {"ok": not codes, "codes": codes, "reasons": reasons, "metrics": metrics,
            "schema": A12_H_GUARD_SCHEMA}


# ---------------------------------------------------------------- 12k artifact guard
def g12_artifact_guard(artifact_dir, provenance_path=None, registry=None, live=True,
                       require_provenance=True, require_f64=True):
    """Fail-closed guard for a [mimo12k] artifact directory (task-255).

    Live 12k G must carry: byte-identical params.json + g f32/f64 content binding,
    resamp filter sha, a real measured-H provenance with a passing H guard, a design
    summary binding (H sha / g_pure sha / taps / D12), and no synthetic/dry-run markers
    or registered synthetic sha/content (max|dG| <= 1e-12).
    """
    reg = registry or synthetic_registry_12k()
    codes, reasons, metrics = [], {}, {}
    adir = os.path.abspath(os.fspath(artifact_dir))
    metrics["artifact_dir"] = adir
    pj = os.path.join(adir, "params.json")
    if not os.path.isfile(pj):
        _code_fail(codes, reasons, "a12_missing_params", "artifact has no params.json")
        return _verdict_12k(codes, reasons, metrics)
    params = load_json(pj, None)
    if not isinstance(params, dict):
        _code_fail(codes, reasons, "a12_bad_params", "params.json is not a JSON object")
        return _verdict_12k(codes, reasons, metrics)
    metrics["params_sha256"] = sha256_file(pj)
    missing = [k for k in A12_PARAMS_REQUIRED if k not in params]
    if missing:
        _code_fail(codes, reasons, "a12_params_missing_fields",
                   "params.json missing required provenance fields: %s" % (missing,))
        metrics["params_missing_fields"] = missing
    schema = str(params.get("schema") or "")
    if schema and not schema.startswith("tspi-mimo-12k"):
        _code_fail(codes, reasons, "a12_params_schema",
                   "params.schema %r is not a tspi-mimo-12k artifact schema" % schema)
    taps = _as_int(params.get("taps"))
    d12 = _as_int(params.get("d12"))
    group = _as_int(params.get("group"))
    fs = _as_int(params.get("fs_hz"))
    lowrate = _as_int(params.get("lowrate_hz"))
    dsys = _as_int(params.get("dsys_samples"))
    rtaps = _as_int(params.get("resamp_taps"))
    rdelay = _as_int(params.get("resamp_delay"))
    parts = [str(p) for p in (params.get("participants") or [])]
    if taps != A12_TAPS:
        _code_fail(codes, reasons, "a12_params_inconsistent",
                   "params.taps=%s, expected %d" % (taps, A12_TAPS))
    if d12 != A12_D12:
        _code_fail(codes, reasons, "a12_params_inconsistent",
                   "params.d12=%s, expected %d" % (d12, A12_D12))
    if group != A12_GROUP or fs != A12_FS_48 or lowrate != A12_FS_12:
        _code_fail(codes, reasons, "a12_params_inconsistent",
                   "params fs/lowrate/group=%s/%s/%s, expected %d/%d/%d"
                   % (fs, lowrate, group, A12_FS_48, A12_FS_12, A12_GROUP))
    if rtaps != A12_RESAMP_TAPS:
        _code_fail(codes, reasons, "a12_params_inconsistent",
                   "params.resamp_taps=%s, expected %d" % (rtaps, A12_RESAMP_TAPS))
    if parts != A12_PARTICIPANTS:
        _code_fail(codes, reasons, "a12_params_participants",
                   "params.participants=%s, expected %s" % (parts, A12_PARTICIPANTS))
    if rdelay is not None and d12 is not None and group is not None \
            and dsys is not None and dsys != 2 * rdelay + group * d12:
        _code_fail(codes, reasons, "a12_params_delay",
                   "params.dsys_samples=%s != 2*resamp_delay+group*d12=%d"
                   % (dsys, 2 * rdelay + group * d12))
    # ---- coefficient content ----
    g_file = str(params.get("g_file") or "")
    g_path = os.path.join(adir, g_file) if g_file else ""
    g32 = None
    if not g_file or not os.path.isfile(g_path):
        _code_fail(codes, reasons, "a12_missing_g_file", "g file missing: %r" % g_file)
    else:
        metrics["g_file"] = g_file
        metrics["g_file_sha256"] = sha256_file(g_path)
        n_parts = len(parts) if parts else len(A12_PARTICIPANTS)
        n_taps = taps if taps else A12_TAPS
        expect_bytes = n_parts * n_parts * n_taps * 4
        if os.path.getsize(g_path) != expect_bytes:
            _code_fail(codes, reasons, "a12_g_file_size",
                       "g bytes=%d != M*M*taps*4=%d" % (os.path.getsize(g_path), expect_bytes))
        else:
            g32 = _load_f32(g_path, (n_parts, n_parts, n_taps))
            metrics["g_f32_content_sha256"] = _sha256_f64_array(g32)
            if not np.all(np.isfinite(g32)):
                _code_fail(codes, reasons, "a12_g_nonfinite", "g contains NaN/Inf")
            if n_parts == len(A12_PARTICIPANTS):
                eye = np.eye(len(A12_PARTICIPANTS), dtype=bool)
                off = float(np.max(np.abs(g32[~eye]))) if np.any(~eye) else 0.0
                metrics["offdiag_peak"] = off
                if off <= A12_G_MATCH_ATOL:
                    _code_fail(codes, reasons, "a12_identity_only",
                               "12k G has no off-diagonal correction (identity plan)")
    r_file = str(params.get("resamp_file") or "")
    r_path = os.path.join(adir, r_file) if r_file else ""
    if not r_file or not os.path.isfile(r_path):
        _code_fail(codes, reasons, "a12_missing_resamp_file", "resamp file missing: %r" % r_file)
    else:
        metrics["resamp_file"] = r_file
        metrics["resamp_sha256"] = sha256_file(r_path)
        if rtaps is not None and os.path.getsize(r_path) != rtaps * 4:
            _code_fail(codes, reasons, "a12_resamp_file_size",
                       "resamp bytes=%d != resamp_taps*4=%d"
                       % (os.path.getsize(r_path), rtaps * 4))
    # ---- provenance record ----
    pp = provenance_path or os.path.join(adir, "provenance.json")
    prov = load_json(pp, None)
    metrics["provenance"] = pp
    metrics["provenance_present"] = isinstance(prov, dict)
    if not isinstance(prov, dict):
        if require_provenance:
            _code_fail(codes, reasons, "a12_missing_provenance",
                       "artifact has no provenance.json (cannot prove a real measured-H design)")
        return _verdict_12k(codes, reasons, metrics)
    pschema = str(prov.get("schema") or "")
    if pschema and pschema != A12_ART_PROV_SCHEMA:
        _code_fail(codes, reasons, "a12_provenance_schema",
                   "provenance.schema %r != %r" % (pschema, A12_ART_PROV_SCHEMA))
    if prov.get("synthetic") is True:
        _code_fail(codes, reasons, "a12_synthetic_marker", "provenance.synthetic=true")
    if _claim_12k_tags_synthetic(prov.get("claim")):
        _code_fail(codes, reasons, "a12_synthetic_marker",
                   "provenance.claim tags the artifact synthetic/dry-run")
    art = prov.get("artifact") or {}
    if not isinstance(art, dict):
        art = {}
    if art.get("params_sha256") and metrics.get("params_sha256") \
            and art["params_sha256"] != metrics["params_sha256"]:
        _code_fail(codes, reasons, "a12_params_sha_mismatch",
                   "provenance.artifact.params_sha256 does not match params.json bytes")
    if g32 is not None:
        if art.get("g_file_sha256") and metrics.get("g_file_sha256") \
                and art["g_file_sha256"] != metrics["g_file_sha256"]:
            _code_fail(codes, reasons, "a12_g_file_sha_mismatch",
                       "provenance.artifact.g_file_sha256 does not match the g f32 bytes")
        if art.get("g_f32_content_sha256") and metrics.get("g_f32_content_sha256") \
                and art["g_f32_content_sha256"] != metrics["g_f32_content_sha256"]:
            _code_fail(codes, reasons, "a12_g_content_mismatch",
                       "provenance.artifact.g_f32_content_sha256 does not match the g samples")
    if metrics.get("resamp_sha256") and art.get("resamp_sha256") \
            and art["resamp_sha256"] != metrics["resamp_sha256"]:
        _code_fail(codes, reasons, "a12_resamp_sha_mismatch",
                   "provenance.artifact.resamp_sha256 does not match resamp bytes")
    for key in ("taps", "d12", "participants"):
        if art.get(key) is not None and params.get(key) is not None \
                and art.get(key) != params.get(key):
            _code_fail(codes, reasons, "a12_artifact_params_mismatch",
                       "provenance.artifact.%s %r != params.%s %r"
                       % (key, art.get(key), key, params.get(key)))
    # g_pure sha (f64 design-domain content) + f64 copy binding
    g_pure_sha = str(art.get("g_pure_sha256") or "")
    params_g_sha = str(params.get("g_sha256") or "")
    if params_g_sha:
        metrics["g_pure_sha256"] = params_g_sha
    if params_g_sha and g_pure_sha and params_g_sha != g_pure_sha:
        _code_fail(codes, reasons, "a12_g_pure_sha_mismatch",
                   "provenance.artifact.g_pure_sha256 != params.g_sha256")
    if not g_pure_sha and not params_g_sha:
        _code_fail(codes, reasons, "a12_missing_g_sha",
                   "no g_pure_sha256 in provenance and no g_sha256 in params.json")
    f64name = str(art.get("g_f64_npz") or "")
    if not f64name:
        if live and require_f64:
            _code_fail(codes, reasons, "a12_missing_g_f64",
                       "no g12_v2_4096.f64.npz content copy: f32 samples cannot be bound to "
                       "the f64 design-domain g_pure_sha256")
    else:
        f64_path = os.path.join(adir, f64name)
        if not os.path.isfile(f64_path):
            _code_fail(codes, reasons, "a12_missing_g_f64", "g f64 copy missing: %s" % f64name)
        else:
            metrics["g_f64_npz"] = f64name
            metrics["g_f64_npz_sha256"] = sha256_file(f64_path)
            if art.get("g_f64_npz_sha256") and art["g_f64_npz_sha256"] != metrics["g_f64_npz_sha256"]:
                _code_fail(codes, reasons, "a12_g_f64_sha_mismatch",
                           "provenance.artifact.g_f64_npz_sha256 does not match the npz bytes")
            try:
                z = load_npz(f64_path)
                f64 = np.asarray(z.get("g_pure")) if "g_pure" in z else None
            except (OSError, ValueError):
                f64 = None
            if f64 is None or f64.ndim != 3:
                _code_fail(codes, reasons, "a12_g_f64_shape", "g f64 npz has no 3-D g_pure")
            else:
                metrics["g_f64_sha256"] = _sha256_f64_array(f64)
                if g_pure_sha and metrics["g_f64_sha256"] != g_pure_sha:
                    _code_fail(codes, reasons, "a12_g_pure_sha_mismatch",
                               "g f64 content sha does not match provenance/params g_pure sha")
                if g32 is not None and f64.shape == g32.shape:
                    scale = max(1.0, float(np.max(np.abs(f64))))
                    d = float(np.max(np.abs(f64 - g32)))
                    metrics["g_f64_vs_f32_max_abs"] = d
                    if d > 1.2e-7 * scale:
                        _code_fail(codes, reasons, "a12_g_content_mismatch",
                                   "g f32 samples differ from the f64 design content by %.3g"
                                   % d)
    # ---- H provenance ----
    h = prov.get("h") or {}
    if not isinstance(h, dict):
        h = {}
    h_sha = str(h.get("sha256") or "")
    metrics["h_sha256"] = h_sha or None
    if not h_sha:
        _code_fail(codes, reasons, "a12_missing_h_provenance",
                   "provenance has no H sha256/record: cannot prove a real measured-H design")
    if live:
        hsrc = str(h.get("source") or h.get("npz") or "")
        if hsrc and (_is_under(hsrc, reg.get("synthetic_roots") or [])
                     or "/prep/dryrun/" in hsrc.replace("\\", "/")):
            _code_fail(codes, reasons, "a12_dryrun_source",
                       "H source is under the dry-run root: %s" % hsrc)
    if h_sha and h_sha in (reg.get("synthetic_h_sha256") or {}).values():
        _code_fail(codes, reasons, "a12_synthetic_h_sha",
                   "H sha256 is a registered synthetic (dry-run) H")
    hg = h.get("guard") or {}
    if live and hg.get("ok") is not True:
        _code_fail(codes, reasons, "a12_h_guard_not_pass",
                   "provenance H guard is missing/not-ok: %s" % (hg.get("codes"),))
    hnpz = str(h.get("npz") or h.get("source") or "")
    if hnpz and os.path.isfile(hnpz):
        if h_sha and sha256_file(hnpz) != h_sha:
            _code_fail(codes, reasons, "a12_h_sha_mismatch",
                       "H file sha256 does not match the provenance record")
        hv = h12_source_check(hnpz, fs_hz=A12_FS_48)
        metrics["h_source_check"] = hv
        if not hv["ok"]:
            for c in hv["codes"]:
                _code_fail(codes, reasons, c, hv["reasons"].get(c))
    elif live and h_sha:
        _code_fail(codes, reasons, "a12_h_source_missing",
                   "H npz not available for revalidation: %s" % hnpz)
    # ---- design-summary binding ----
    d = prov.get("design") or {}
    if not isinstance(d, dict):
        d = {}
    summ_path = str(d.get("summary_json") or "")
    if not summ_path:
        _code_fail(codes, reasons, "a12_missing_design_summary",
                   "provenance has no design summary binding")
    elif not os.path.isfile(os.path.join(adir, summ_path) if not os.path.isabs(summ_path)
                            else summ_path):
        _code_fail(codes, reasons, "a12_missing_design_summary",
                   "design summary not found: %s" % summ_path)
    else:
        spath = summ_path if os.path.isabs(summ_path) else os.path.join(adir, summ_path)
        metrics["design_summary"] = spath
        metrics["design_summary_sha256"] = sha256_file(spath)
        if d.get("summary_sha256") and d["summary_sha256"] != metrics["design_summary_sha256"]:
            _code_fail(codes, reasons, "a12_design_summary_sha_mismatch",
                       "design summary sha256 does not match the provenance record")
        summ = load_json(spath, None)
        if not isinstance(summ, dict):
            _code_fail(codes, reasons, "a12_bad_design_summary", "design summary unreadable")
        else:
            si = summ.get("inputs") or {}
            if h_sha and si.get("h_sha256") and si["h_sha256"] != h_sha:
                _code_fail(codes, reasons, "a12_design_h_binding",
                           "design summary inputs.h_sha256 != provenance H sha256")
            v2 = summ.get("v2_12k") or {}
            if v2.get("g_pure_sha256") and params_g_sha \
                    and v2["g_pure_sha256"] != params_g_sha:
                _code_fail(codes, reasons, "a12_design_g_binding",
                           "design summary v2_12k.g_pure_sha256 != params.g_sha256")
            if v2.get("taps") is not None and taps is not None and _as_int(v2["taps"]) != taps:
                _code_fail(codes, reasons, "a12_design_taps",
                           "design summary taps=%s != params.taps=%s" % (v2["taps"], taps))
            delay = summ.get("delay") or {}
            if delay.get("d12") is not None and d12 is not None and _as_int(delay["d12"]) != d12:
                _code_fail(codes, reasons, "a12_design_d12",
                           "design summary d12=%s != params.d12=%s" % (delay["d12"], d12))
    # ---- registered synthetic sha/content (<=1e-12) ----
    if g32 is not None:
        if metrics.get("g_file_sha256") in (reg.get("synthetic_g12_file_sha256") or {}).values():
            _code_fail(codes, reasons, "a12_synthetic_file_sha",
                       "g f32 file sha256 is a registered synthetic 12k fixture hash")
        for key, arr in synthetic_g12_arrays().items():
            if arr.shape != g32.shape:
                continue
            dd = float(np.max(np.abs(arr - g32)))
            metrics["g12_max_abs_vs_" + key] = dd
            if dd <= A12_G_MATCH_ATOL:
                _code_fail(codes, reasons, "a12_synthetic_content",
                           "12k G is identical (<=1e-12) to synthetic fixture %s" % key)
    return _verdict_12k(codes, reasons, metrics)


def _verdict_12k(codes, reasons, metrics):
    for c in codes:
        reasons.setdefault(c, _A12_REASON_TEXT.get(c, c))
    return {"ok": not codes, "codes": codes, "reasons": reasons, "metrics": metrics,
            "schema": "tspi-mimo-12k-guard-verdict/v1"}


# ---------------------------------------------------------------- 12k plan guard
def g12_plan_guard(plan_dir, artifact_dir=None, provenance_path=None, registry=None,
                   live=True, require_provenance=True):
    """Fail-closed guard for a 12k plan directory (plan.bin + compile-report.json).

    Binds the plan bytes to the compile report and to the guarded [mimo12k] artifact:
    plan sha == compile-report.plan_sha256, plan-provenance record with matching artifact
    hashes + artifact-guard passport; missing provenance is refused.
    """
    reg = registry or synthetic_registry_12k()
    codes, reasons, metrics = [], {}, {}
    pdir = os.path.abspath(os.fspath(plan_dir))
    metrics["plan_dir"] = pdir
    plan_path = os.path.join(pdir, "plan.bin")
    if not os.path.isfile(plan_path):
        raise FileNotFoundError(plan_path)
    sha = sha256_file(plan_path)
    metrics["plan_sha256"] = sha
    metrics["plan_bytes"] = os.path.getsize(plan_path)
    rep_path = os.path.join(pdir, "compile-report.json")
    rep = load_json(rep_path, None) if os.path.isfile(rep_path) else None
    if not isinstance(rep, dict):
        _code_fail(codes, reasons, "a12_plan_missing_compile_report",
                   "plan dir has no compile-report.json: plan bytes are unbound")
    else:
        metrics["compile_report"] = rep_path
        metrics["compile_report_sha256"] = sha256_file(rep_path)
        claimed = ((rep.get("plan") or {}).get("plan_sha256") or rep.get("plan_sha256"))
        if not claimed:
            _code_fail(codes, reasons, "a12_plan_missing_compile_report",
                       "compile-report.json carries no plan_sha256")
        elif str(claimed).lower() != sha.lower():
            _code_fail(codes, reasons, "a12_plan_sha_mismatch",
                       "compile-report plan_sha256 does not match plan.bin bytes")
            metrics["compile_report_plan_sha256"] = claimed
        if rep.get("plan_bytes") is not None \
                and _as_int(rep["plan_bytes"]) != metrics["plan_bytes"]:
            _code_fail(codes, reasons, "a12_plan_bytes_mismatch",
                       "compile-report plan_bytes does not match plan.bin size")
        if rep.get("synthetic") is True:
            _code_fail(codes, reasons, "a12_plan_report_synthetic",
                       "compile-report is tagged synthetic")
        for key in ("claim", "design_claim", "compiler_note"):
            if _claim_12k_tags_synthetic(rep.get(key)):
                _code_fail(codes, reasons, "a12_plan_report_synthetic",
                           "compile-report %s tags the plan synthetic/dry-run" % key)
        metrics["design_source"] = rep.get("design_source") or rep.get("design_source_dir")
    pp = provenance_path or os.path.join(pdir, "plan-provenance.json")
    prov = load_json(pp, None)
    metrics["provenance"] = pp
    metrics["provenance_present"] = isinstance(prov, dict)
    if not isinstance(prov, dict):
        if require_provenance:
            _code_fail(codes, reasons, "a12_plan_missing_provenance",
                       "plan has no plan-provenance.json binding it to a guarded 12k artifact")
        return _verdict_12k(codes, reasons, metrics)
    pschema = str(prov.get("schema") or "")
    if pschema and pschema != A12_PLAN_PROV_SCHEMA:
        _code_fail(codes, reasons, "a12_plan_provenance_schema",
                   "plan provenance schema %r != %r" % (pschema, A12_PLAN_PROV_SCHEMA))
    if prov.get("synthetic") is True:
        _code_fail(codes, reasons, "a12_plan_synthetic", "plan provenance.synthetic=true")
    if prov.get("plan_sha256") and str(prov["plan_sha256"]).lower() != sha.lower():
        _code_fail(codes, reasons, "a12_plan_provenance_sha_mismatch",
                   "plan provenance plan_sha256 does not match plan.bin bytes")
    metrics["plan_provenance_ok"] = True
    if metrics.get("compile_report_sha256") and prov.get("compile_report_sha256") \
            and prov["compile_report_sha256"] != metrics["compile_report_sha256"]:
        _code_fail(codes, reasons, "a12_plan_compile_report_mismatch",
                   "plan provenance compile_report_sha256 does not match compile-report.json")
    art = prov.get("mimo12k_artifact") or {}
    if not isinstance(art, dict):
        art = {}
    ag = prov.get("artifact_guard") or {}
    if ag.get("ok") is not True:
        _code_fail(codes, reasons, "a12_plan_artifact_guard_not_pass",
                   "plan provenance artifact_guard.ok is not true")
    adir = artifact_dir or art.get("artifact_dir")
    if not adir:
        _code_fail(codes, reasons, "a12_plan_missing_artifact_binding",
                   "plan provenance has no [mimo12k] artifact binding")
        return _verdict_12k(codes, reasons, metrics)
    if live and not os.path.isdir(os.path.abspath(str(adir))):
        _code_fail(codes, reasons, "a12_plan_missing_artifact_binding",
                   "bound [mimo12k] artifact dir not available for revalidation: %s" % adir)
        return _verdict_12k(codes, reasons, metrics)
    av = g12_artifact_guard(adir, registry=reg, live=live)
    metrics["artifact_guard"] = av
    if not av["ok"]:
        for c in av["codes"]:
            _code_fail(codes, reasons, c, av["reasons"].get(c))
        _code_fail(codes, reasons, "a12_plan_artifact_guard_not_pass",
                   "bound [mimo12k] artifact does not pass the artifact guard")
    am = av["metrics"]
    pairs = (("params_sha256", am.get("params_sha256")),
             ("g_file_sha256", am.get("g_file_sha256")),
             ("g_f32_content_sha256", am.get("g_f32_content_sha256")),
             ("g_pure_sha256", am.get("g_pure_sha256")),
             ("resamp_sha256", am.get("resamp_sha256")),
             ("h_sha256", am.get("h_sha256")))
    for key, actual in pairs:
        recorded = art.get(key)
        if recorded and actual and str(recorded) != str(actual):
            _code_fail(codes, reasons, "a12_plan_artifact_mismatch",
                       "plan provenance %s does not match the guarded artifact" % key)
    return _verdict_12k(codes, reasons, metrics)


