    p.add_argument("--artifact", default=None)
    p.add_argument("--provenance", default=None)
    p.add_argument("--json-out", default=None)
    args = ap.parse_args(argv)
    if args.cmd == "registry":
        _emit(synthetic_registry(), args.out)
        return 0
    if args.cmd == "check-h":
        if args.h.endswith(".npz"):
            arrs = load_npz(args.h)
            h = {"freq": arrs.get("freq"), "H_norm": arrs.get("H_norm"), "irs": arrs.get("irs"),
                 "mic_names": [str(x) for x in arrs.get("mic_names", [])] or None,
                 "info": load_json(os.path.join(os.path.dirname(args.h), "h_estimate.json"), {}) or {}}
            h["info"]["mic_names"] = h["mic_names"]
        else:
            h = load_json(args.h)
        v = h_guard(h)
        _emit(v, args.json_out)
        return 0 if v["ok"] else 3
    if args.cmd == "check-design":
        v = g_guard(args.design, live=args.live)
        _emit(v, args.json_out)
        return 0 if v["ok"] else 3
    if args.cmd == "check-plan":
        v = g_guard_plan(args.plan, args.compile_report, design=args.design)
        _emit(v, args.json_out)
        return 0 if v["ok"] else 3
    if args.cmd == "registry-12k":
        _emit(synthetic_registry_12k(), args.out)
        return 0
    if args.cmd == "check-12k-h":
        v = h12_source_check(args.h)
        _emit(v, args.json_out)
        return 0 if v["ok"] else 3
    if args.cmd == "check-12k-artifact":
        v = g12_artifact_guard(args.artifact, provenance_path=args.provenance, live=True)
        _emit(v, args.json_out)
        return 0 if v["ok"] else 3
    if args.cmd == "check-12k-plan":
        v = g12_plan_guard(args.plan_dir, artifact_dir=args.artifact,
                           provenance_path=args.provenance, live=True)
        _emit(v, args.json_out)
        return 0 if v["ok"] else 3
    return 2


