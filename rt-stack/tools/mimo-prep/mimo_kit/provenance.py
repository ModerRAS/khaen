# ---------------------------------------------------------------- chain helper
def resolve_design_source(summary, live, dryrun_design_dir, design_key="design",
                          registry=None):
    """The fixed run_0830.step_t66_compile source resolution (no silent fallback).

    summary: run summary dict (summary["design"]["source"] is the real design dir).
    live:    True for a board/live run -- a missing/non-real source REFUSES.
    dryrun_design_dir: prep/dryrun/out/design, only legal when live is False.
    """
    src = ((summary or {}).get(design_key) or {}).get("source")
    if not src:
        if live:
            raise ProvenanceRefusal("live_no_design_source",
                                    {"detail": "summary['%s']['source'] missing" % design_key})
        return os.path.abspath(dryrun_design_dir)
    src = os.path.abspath(str(src))
    if live and _is_under(src, (synthetic_registry() if registry is None else registry).get("synthetic_roots") or []):
        raise ProvenanceRefusal("g_h_dryrun_source", {"design_source": src})
    if live:
        verdict = g_guard(src, registry, live=True)
        if not verdict["ok"]:
            raise ProvenanceRefusal(verdict["codes"], {"design_source": src, "guard": verdict})
    return src


