def g_guard_plan(plan_path, compile_report_path=None, design=None, registry=None, live=True):
    reg = registry or synthetic_registry()
    codes, reasons, metrics = [], {}, {}
    plan_path = os.fspath(plan_path)
    if not os.path.isfile(plan_path):
        raise FileNotFoundError(plan_path)
    sha = sha256_file(plan_path)
    metrics["plan_sha256"] = sha
    metrics["plan_bytes"] = os.path.getsize(plan_path)
    if sha in (reg.get("synthetic_plan_sha256") or {}).values():
        codes.append("g_plan_synthetic_sha")
    rep_path = compile_report_path
    if rep_path is None:
        cand = os.path.join(os.path.dirname(os.path.abspath(plan_path)), "compile-report.json")
        rep_path = cand if os.path.isfile(cand) else None
    rep = load_json(rep_path) if rep_path else None
    metrics["compile_report"] = rep_path
    if isinstance(rep, dict):
        claimed = ((rep.get("plan") or {}).get("plan_sha256") or rep.get("plan_sha256"))
        if claimed and str(claimed).lower() != sha.lower():
            codes.append("g_plan_sha_mismatch")
            metrics["compile_report_plan_sha256"] = claimed
        if rep.get("synthetic") is True:
            codes.append("g_plan_report_synthetic")
        src = str(rep.get("design_source") or rep.get("design_source_dir") or "")
        ds = rep.get("design_source") if isinstance(rep.get("design_source"), str) else ""
        if src and (_is_under(src, reg.get("synthetic_roots") or [])
                    or "/prep/dryrun/" in src.replace("\\", "/")):
            codes.append("g_plan_synthetic_design")
        shas = rep.get("design_sha256") or rep.get("source_design_sha256")
        if isinstance(shas, str) and shas in (reg.get("synthetic_design_sha256") or {}).values():
            codes.append("g_plan_synthetic_design")
        metrics["design_source"] = ds or src or None
    if design is not None:
        d = g_guard(design, reg, live=live)
        if not d["ok"]:
            codes.extend(d["codes"])
            metrics["design_guard"] = d
    if design is None and live:
        # cannot prove the plan came from a real design
        codes.append("g_missing_provenance")
    for c in codes:
        reasons.setdefault(c, _REASON_TEXT.get(c, c))
    return {"ok": not codes, "codes": codes, "reasons": reasons, "metrics": metrics}


