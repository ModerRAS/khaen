def _is_under(path, roots):
    if not path:
        return False
    p = os.path.normpath(os.path.abspath(str(path))).lower().replace("\\", "/")
    for r in roots:
        rn = os.path.normpath(os.path.abspath(str(r))).lower().replace("\\", "/")
        if p == rn or p.startswith(rn + "/"):
            return True
    return False


# ---------------------------------------------------------------- H guard
def _ir_array(h):
    """Normalize h['irs'] to (n_mics, 7, nsamp) float array (missing slots -> zeros)."""
    irs = h.get("irs")
    if irs is None:
        return None
    if isinstance(irs, np.ndarray):
        return np.asarray(irs, dtype=np.float64)
    if isinstance(irs, dict):  # mic -> {slot: ir}
        names = list(h.get("mic_names") or (h.get("info") or {}).get("mic_names") or irs.keys())
        nsamp = 0
        for m in names:
            for v in (irs.get(m) or {}).values():
                nsamp = max(nsamp, len(np.asarray(v)))
        out = np.zeros((len(names), len(rd.OUTPUTS), nsamp))
        for mi, m in enumerate(names):
            for slot, v in (irs.get(m) or {}).items():
                out[mi, int(slot), :len(np.asarray(v))] = np.asarray(v, dtype=np.float64)
        return out
    return None


def h_guard(h, registry=None, live=True):
    """Validate an estimated-H bundle before it may drive a real design."""
    codes, reasons, metrics = [], {}, {}

    def bad(code, msg):
        codes.append(code)
        reasons[code] = msg

    reg = registry or synthetic_registry()
    info = dict(h.get("info") or {})
    mic_names = [str(m) for m in (info.get("mic_names") or h.get("mic_names") or rd.DESIGN_MICS)]
    freqs = np.asarray(h.get("freq"))
    Hn = np.asarray(h.get("H_norm"))
    metrics["mic_names"] = mic_names
    if freqs.ndim != 1 or freqs.size < 8:
        bad("h_bad_freq_grid", "H freq grid missing/short")
    if Hn.ndim != 3 or Hn.shape[1] != len(rd.OUTPUTS):
        bad("h_bad_shape", "H_norm must be (n_mics, 7, nf) in OUTPUTS order, got %s" % (Hn.shape,))
    if not mic_names or len(mic_names) < 3:
        bad("h_insufficient_mics", "need >=3 design mics (UMIK/MA1/ARC), got %s" % (mic_names,))
    for m in ("UMIK", "MA1", "ARC"):
        if m not in mic_names:
            bad("h_missing_mic", "required design mic %s missing (got %s)" % (m, mic_names))
    if Hn.ndim == 3 and np.any(~np.isfinite(Hn)):
        bad("h_nonfinite", "H_norm contains NaN/Inf")

    # H source provenance: dry-run / synthetic fixtures are never a live design source
    if live:
        if info.get("synthetic") is True:
            bad("h_synthetic_source", "H info.synthetic=true")
        src = info.get("arm") or info.get("session") or h.get("arm") or ""
        if _is_under(src, reg.get("synthetic_roots") or []) or "/prep/dryrun/" in str(src).replace("\\", "/"):
            bad("h_dryrun_source", "H source under dry-run root: %s" % src)
        if info.get("h_sha256") and info["h_sha256"] in (reg.get("synthetic_h_sha256") or {}).values():
            bad("h_synthetic_fixture_sha", "H file sha in synthetic registry")

    # mic availability + the known MA1/ARC byte-mapping artifact signature
    stats = info.get("mic_stats") or h.get("mic_stats") or {}
    metrics["mic_stats"] = {}
    for mi, m in enumerate(mic_names):
        st = stats.get(m) or {}
        peak = _f(st.get("peak_dbfs"))
        snr = _f(st.get("snr_db"))
        avail = st.get("available")
        metrics["mic_stats"][m] = {"peak_dbfs": peak, "snr_db": snr, "available": avail}
        if peak is not None and ARTIFACT_PEAK_RANGE_DBFS[0] <= peak <= ARTIFACT_PEAK_RANGE_DBFS[1] \
                and snr is not None and snr < ARTIFACT_MAX_SNR_DB:
            bad("h_mic_byte_artifact",
                "%s shows the S24 byte-mapping artifact signature (peak %.2f dBFS, SNR %.2f dB)"
                % (m, peak, snr))
            continue
        if avail is False or (peak is not None and peak <= MIC_MIN_PEAK_DBFS) \
                or (snr is not None and snr < MIC_MIN_SNR_DB):
            bad("h_mic_unavailable",
                "%s unusable for design (peak=%s dBFS snr=%s dB)" % (m, peak, snr))

    # IR direct-arrival checks (peak window + spread)
    irs = _ir_array(h)
    ir_metrics = {}
    if irs is None:
        bad("h_missing_irs", "h['irs'] missing; cannot validate IR peaks")
    else:
        fs = float(info.get("fs_hz") or 48000.0)
        max_peak = int(round(IR_MAX_PEAK_MS / 1000.0 * fs))
        max_spread = int(round(IR_MAX_PEAK_SPREAD_MS / 1000.0 * fs))
        peaks = {}
        for mi, m in enumerate(mic_names):
            if mi >= irs.shape[0]:
                continue
            row = {}
            for role, oi in PARTICIPANT_ROWS.items():
                ir = irs[mi, oi]
                if ir.size == 0 or not np.any(ir):
                    continue
                k = int(np.argmax(np.abs(ir)))
                row[role] = k
                if k > max_peak:
                    bad("h_ir_peak_out_of_window",
                        "%s/%s IR peak at %.1f ms (> %.0f ms)" % (m, role, k / fs * 1000.0, IR_MAX_PEAK_MS))
            peaks[m] = row
            vals = list(row.values())
            if len(vals) >= 2 and (max(vals) - min(vals)) > max_spread:
                bad("h_ir_peak_spread",
                    "%s IR peaks span %d samples (> %d) across roles" % (m, max(vals) - min(vals), max_spread))
        for role in PARTICIPANT_ROWS:
            vals = [peaks[m][role] for m in peaks if role in peaks[m]]
            if len(vals) >= 2 and (max(vals) - min(vals)) > max_spread:
                bad("h_ir_peak_spread",
                    "%s IR peaks span %d samples across mics (> %d)" % (role, max(vals) - min(vals), max_spread))
        ir_metrics = {"peaks_samples": peaks,
                      "max_peak_allowed_samples": max_peak,
                      "max_spread_allowed_samples": max_spread}
    metrics["irs"] = ir_metrics

    # dead participant rows (a design cannot correct a source with no measured energy)
    if Hn.ndim == 3:
        row_db = {}
        for role, oi in PARTICIPANT_ROWS.items():
            vals = Hn[:, oi, :]
            v = float(np.max(np.abs(vals))) if vals.size else 0.0
            row_db[role] = 20.0 * math.log10(v + 1e-300)
            if not np.isfinite(row_db[role]) or row_db[role] <= H_MIN_ABS_DB:
                bad("h_dead_participant_row", "participant %s H is dead (%.1f dB)" % (role, row_db[role]))
        metrics["H_max_abs_db_per_participant"] = row_db

    return {"ok": not codes, "codes": codes, "reasons": reasons, "metrics": metrics,
            "policy": {"mic_min_peak_dbfs": MIC_MIN_PEAK_DBFS, "mic_min_snr_db": MIC_MIN_SNR_DB,
                       "artifact_peak_range_dbfs": list(ARTIFACT_PEAK_RANGE_DBFS),
                       "artifact_max_snr_db": ARTIFACT_MAX_SNR_DB,
                       "ir_max_peak_ms": IR_MAX_PEAK_MS,
                       "ir_max_peak_spread_ms": IR_MAX_PEAK_SPREAD_MS}}


# ---------------------------------------------------------------- G guard
def _candidate_arrays(design):
    if isinstance(design, dict):
        return design
    if isinstance(design, (str, os.PathLike)):
        p = os.fspath(design)
        if os.path.isdir(p):
            p = os.path.join(p, "g_design.npz")
        if not os.path.isfile(p):
            raise FileNotFoundError(p)
        return load_npz(p)
    raise TypeError("design must be npz path/dir or dict")


def g_content_checks(arrs, registry=None):
    """Return (synthetic_codes, metrics) for a G coefficient bundle."""
    reg = registry or synthetic_registry()
    codes, metrics = [], {}
    G_ideal = np.asarray(arrs.get("G_ideal")) if "G_ideal" in arrs else None
    G_fir = np.asarray(arrs.get("G_fir")) if "G_fir" in arrs else None
    dry = None
    if reg.get("dryrun_design_npz"):
        try:
            dry = load_npz(reg["dryrun_design_npz"]["path"])
        except OSError:
            dry = None
    if dry is not None:
        syn = np.asarray(dry["G_ideal"])
        # 7x7 content equality (what gen_plans.py realized from)
        if G_ideal is not None and G_ideal.shape == syn.shape:
            d = np.max(np.abs(np.asarray(G_ideal) - syn))
            metrics["G_ideal_max_abs_vs_dryrun"] = float(d)
            if d <= G_MATCH_ATOL:
                codes.append("g_synthetic_content")
        # 5x5 participant subset (participant order FL,FR,SL,SR,SUB1)
        if G_ideal is not None and G_ideal.shape == (len(PARTICIPANTS), len(PARTICIPANTS), syn.shape[2]):
            sel = [rd.participant_index(p) for p in PARTICIPANTS]
            d = np.max(np.abs(np.asarray(G_ideal) - syn[np.ix_(sel, sel)]))
            metrics["G_ideal_max_abs_vs_dryrun_5x5"] = float(d)
            if d <= G_MATCH_ATOL:
                codes.append("g_synthetic_content")
        taps = arrs.get("taps")
        delay = arrs.get("D", arrs.get("delay_samples"))
        if G_fir is not None and taps is not None and delay is not None:
            gf = np.asarray(G_fir, dtype=np.float64)
            taps = int(np.asarray(taps).reshape(-1)[0])
            delay = int(np.asarray(delay).reshape(-1)[0])
            if gf.shape[-1] == taps:
                if gf.shape[0] == syn.shape[0]:
                    real = rd._realize_fir(dry["freq"], syn, taps, delay)
                elif gf.shape[0] == len(PARTICIPANTS):
                    sel = [rd.participant_index(p) for p in PARTICIPANTS]
                    real = rd._realize_fir(dry["freq"], syn[np.ix_(sel, sel)], taps, delay)
                else:
                    real = None
                if real is not None:
                    d = float(np.max(np.abs(gf - real)))
                    metrics["G_fir_max_abs_vs_dryrun_realized"] = d
                    if d <= G_MATCH_ATOL:
                        codes.append("g_synthetic_content")
    # identity-only is not a room design either
    if G_ideal is not None and G_ideal.ndim == 3:
        off = np.array([[G_ideal[i, j] for j in range(G_ideal.shape[1])]
                        for i in range(G_ideal.shape[0])])
        diag_mask = np.eye(G_ideal.shape[0], dtype=bool)
        offdiag = float(np.max(np.abs(G_ideal[~diag_mask]))) if np.any(~diag_mask) else 0.0
        metrics["offdiag_peak"] = offdiag
        if offdiag <= 1e-12:
            codes.append("g_identity_only")
    if G_ideal is not None and np.any(~np.isfinite(G_ideal)):
        codes.append("g_nonfinite")
    return codes, metrics


def g_guard(design, registry=None, live=True, require_provenance=True):
    """Fail-closed G/design guard. design = npz path | design dir | dict of arrays."""
    reg = registry or synthetic_registry()
    codes, reasons, metrics = [], {}, {}
    arrs = _candidate_arrays(design)
    path = os.fspath(design) if isinstance(design, (str, os.PathLike)) else None
    if path and os.path.isdir(path):
        metrics["design_dir"] = os.path.abspath(path)
        npz = os.path.join(path, "g_design.npz")
        if os.path.isfile(npz):
            metrics["g_design_sha256"] = sha256_file(npz)
            if metrics["g_design_sha256"] in (reg.get("synthetic_design_sha256") or {}).values():
                codes.append("g_synthetic_file_sha")
        rep = load_json(os.path.join(path, "design-report.json"))
        metrics["design_report_present"] = rep is not None
        if isinstance(rep, dict):
            if rep.get("synthetic") is True:
                codes.append("g_synthetic_marker")
            claim = str(rep.get("claim") or "").lower()
            if "dry-run" in claim or "synthetic" in claim:
                codes.append("g_synthetic_marker")
            prov = rep.get("provenance") or {}
            metrics["has_provenance"] = bool(prov)
            h_guard_res = prov.get("h_guard") or {}
            if prov and h_guard_res.get("ok") is not True:
                codes.append("g_h_guard_not_pass")
            src = str(prov.get("h_arm") or prov.get("h_source") or "")
            if src and (_is_under(src, reg.get("synthetic_roots") or [])
                        or "/prep/dryrun/" in src.replace("\\", "/")):
                codes.append("g_h_dryrun_source")
            if live and require_provenance and not prov:
                codes.append("g_missing_provenance")
    content_codes, content_metrics = g_content_checks(arrs, reg)
    codes.extend(content_codes)
    metrics.update(content_metrics)
    for c in codes:
        reasons.setdefault(c, _REASON_TEXT.get(c, c))
    return {"ok": not codes, "codes": codes, "reasons": reasons, "metrics": metrics}


